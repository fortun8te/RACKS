/**
 * Unit tests for the Apify fallback in youtubeTranscriptService.ts (no network).
 */
import { jest } from '@jest/globals';
import { YouTubeTranscriptService } from '../youtubeTranscriptService.js';

// Keep the unit isolated from Ollama / storage (and their ESM-only deps)
jest.mock('../ollama.js', () => ({ ollamaService: {} }));
jest.mock('../storageService.js', () => ({ storageService: {} }));

const VIDEO = 'https://www.youtube.com/watch?v=jNQXAC9IVRw';
const OK_ROW = {
  status: 'OK',
  videoId: 'jNQXAC9IVRw',
  title: 'Me at the zoo',
  language: 'en',
  isAutoGenerated: false,
  segments: [
    { start: 1.2, dur: 2.16, text: 'All right, so here we are,' },
    { start: 3.36, dur: 2.5, text: '[Music] in front of the elephants' },
  ],
};

const json = (body: unknown) => ({ ok: true, status: 200, json: async () => body }) as any;

function mockApify(items: unknown[]) {
  const calls: { url: string; body?: any }[] = [];
  (globalThis as any).fetch = jest.fn(async (url: string, init?: any) => {
    calls.push({ url, body: init?.body ? JSON.parse(init.body) : undefined });
    if (url.includes('/acts/')) return json({ data: { id: 'run1' } });
    if (url.includes('/actor-runs/')) return json({ data: { status: 'SUCCEEDED', defaultDatasetId: 'ds1' } });
    return json(items);
  });
  return calls;
}

async function runWithFakeSleep<T>(p: Promise<T>): Promise<T> {
  for (let i = 0; i < 5; i++) await jest.advanceTimersByTimeAsync(5_000);
  return p;
}

describe('YouTubeTranscriptService._fetchViaApify', () => {
  const realFetch = globalThis.fetch;
  beforeEach(() => { jest.useFakeTimers(); process.env.APIFY_TOKEN = 'test-token'; });
  afterEach(() => { jest.useRealTimers(); globalThis.fetch = realFetch; delete process.env.APIFY_TOKEN; });

  it('calls the transcript Actor and maps segments (seconds) to TranscriptSegment[]', async () => {
    const calls = mockApify([OK_ROW]);
    const svc = new YouTubeTranscriptService() as any;
    const result: any = await runWithFakeSleep(svc._fetchViaApify(VIDEO));

    expect(calls[0].url).toContain('/acts/shephouse~youtube-transcript-scraper-bulk/runs');
    expect(calls[0].body).toEqual({ startUrls: [{ url: VIDEO }], languages: ['en'], maxTranscripts: 1 });
    expect(result.segments).toEqual([
      { text: 'All right, so here we are,', start: 1.2, duration: 2.16 },
      { text: 'in front of the elephants', start: 3.36, duration: 2.5 },
    ]);
    expect(result.rawText).toBe('All right, so here we are, in front of the elephants');
    expect(result.title).toBe('Me at the zoo');
    expect(result.language).toBe('en');
    expect(result.isAutoGenerated).toBe(false);
    expect(result.duration).toBeCloseTo(5.86);
  });

  it('returns null for a video without captions', async () => {
    mockApify([{ status: 'FAILED', errorCode: 'NO_CAPTIONS', errorMessage: 'no captions' }]);
    const svc = new YouTubeTranscriptService() as any;
    expect(await runWithFakeSleep(svc._fetchViaApify(VIDEO))).toBeNull();
  });

  it('returns null without calling Apify when APIFY_TOKEN is missing', async () => {
    delete process.env.APIFY_TOKEN;
    const calls = mockApify([OK_ROW]);
    const svc = new YouTubeTranscriptService() as any;
    expect(await svc._fetchViaApify(VIDEO)).toBeNull();
    expect(calls).toHaveLength(0);
  });
});
